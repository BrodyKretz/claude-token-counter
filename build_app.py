"""Build "Claude Tracker.app" so the app shows up in Finder's Applications.

The bundle is a thin launcher: its executable runs app.py from this project
folder with the given Python, so state.json and the logs stay here and
`git pull` updates the app without rebuilding. Rebuild only if you move this
folder or change Python.

Usage:
    python3 build_app.py [--python /path/to/python3] [--dest /Applications]

Prints the path of the bundle's executable as its last line (install.sh
points the start-at-login LaunchAgent at it).
"""

import argparse
import os
import plistlib
import shlex
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from version import APP_NAME, FORK_AUTHOR, ORIGINAL_AUTHOR, __version__

PROJECT_DIR = Path(__file__).resolve().parent
BUNDLE_ID = "com.raymondtian.claudetracker"
EXECUTABLE_NAME = "claude-tracker"
ICON_NAME = "AppIcon"


def info_plist():
    return {
        "CFBundleName": APP_NAME,
        "CFBundleDisplayName": APP_NAME,
        "CFBundleIdentifier": BUNDLE_ID,
        "CFBundleExecutable": EXECUTABLE_NAME,
        "CFBundleIconFile": ICON_NAME,
        "CFBundlePackageType": "APPL",
        "CFBundleShortVersionString": __version__,
        "CFBundleVersion": __version__,
        "CFBundleInfoDictionaryVersion": "6.0",
        "LSMinimumSystemVersion": "11.0",
        # Menu bar only: no Dock icon, no app menu.
        "LSUIElement": True,
        "NSHighResolutionCapable": True,
        "NSHumanReadableCopyright": (
            f"Original app by {ORIGINAL_AUTHOR}. Redesign and new features by {FORK_AUTHOR}."
        ),
    }


def launcher_script(python, project_dir):
    q = shlex.quote
    app_py = project_dir / "app.py"
    return f"""#!/bin/bash
# Generated by build_app.py -- runs Claude Tracker from its project folder.
cd {q(str(project_dir))} || exit 1
exec {q(python)} {q(str(app_py))} >>{q(str(project_dir / "agent.log"))} 2>>{q(str(project_dir / "agent.err.log"))}
"""


def _rgb(r, g, b, a=1.0):
    from AppKit import NSColor

    return NSColor.colorWithCalibratedRed_green_blue_alpha_(r, g, b, a)


def _sparkle(cx, cy, radius):
    """A four-point star (drawn from scratch, no emoji or symbol artwork)."""
    from AppKit import NSBezierPath

    path = NSBezierPath.bezierPath()
    points = [(cx, cy + radius), (cx + radius, cy), (cx, cy - radius), (cx - radius, cy)]
    path.moveToPoint_(points[0])
    for start, end in zip(points, points[1:] + points[:1]):
        # Pull the curve slightly off-center so the arms aren't hairline thin.
        control = (
            cx + ((start[0] + end[0]) / 2 - cx) * 0.22,
            cy + ((start[1] + end[1]) / 2 - cy) * 0.22,
        )
        path.curveToPoint_controlPoint1_controlPoint2_(end, control, control)
    path.closePath()
    return path


def render_icon_png(path, pixels):
    """Draw the app icon, `pixels` wide: a gold coin with a sparkle on a dark
    rounded square."""
    from AppKit import (
        NSBezierPath,
        NSBitmapImageFileTypePNG,
        NSBitmapImageRep,
        NSCalibratedRGBColorSpace,
        NSGradient,
        NSGraphicsContext,
        NSMakeRect,
    )

    rep = NSBitmapImageRep.alloc().initWithBitmapDataPlanes_pixelsWide_pixelsHigh_bitsPerSample_samplesPerPixel_hasAlpha_isPlanar_colorSpaceName_bytesPerRow_bitsPerPixel_(
        None, pixels, pixels, 8, 4, True, False, NSCalibratedRGBColorSpace, 0, 0
    )
    NSGraphicsContext.saveGraphicsState()
    NSGraphicsContext.setCurrentContext_(NSGraphicsContext.graphicsContextWithBitmapImageRep_(rep))
    p = pixels

    # Background: Apple's icon grid puts the rounded square at ~80% of the canvas.
    inset = p * 0.1
    side = p - 2 * inset
    background = NSBezierPath.bezierPathWithRoundedRect_xRadius_yRadius_(
        NSMakeRect(inset, inset, side, side), side * 0.225, side * 0.225
    )
    NSGradient.alloc().initWithStartingColor_endingColor_(
        _rgb(0.20, 0.21, 0.27), _rgb(0.07, 0.07, 0.10)
    ).drawInBezierPath_angle_(background, -90)

    center = p / 2
    # Coin body with a darker rim.
    radius = side * 0.34
    rim = NSBezierPath.bezierPathWithOvalInRect_(
        NSMakeRect(center - radius, center - radius, 2 * radius, 2 * radius)
    )
    NSGradient.alloc().initWithStartingColor_endingColor_(
        _rgb(0.93, 0.68, 0.22), _rgb(0.62, 0.38, 0.08)
    ).drawInBezierPath_angle_(rim, -90)
    face_radius = radius * 0.86
    face = NSBezierPath.bezierPathWithOvalInRect_(
        NSMakeRect(center - face_radius, center - face_radius, 2 * face_radius, 2 * face_radius)
    )
    NSGradient.alloc().initWithStartingColor_endingColor_(
        _rgb(1.00, 0.88, 0.48), _rgb(0.90, 0.62, 0.18)
    ).drawInBezierPath_angle_(face, -90)
    # Thin inner ring.
    ring_radius = face_radius * 0.82
    ring = NSBezierPath.bezierPathWithOvalInRect_(
        NSMakeRect(center - ring_radius, center - ring_radius, 2 * ring_radius, 2 * ring_radius)
    )
    ring.setLineWidth_(max(1.0, p * 0.012))
    _rgb(0.72, 0.47, 0.10, 0.7).setStroke()
    ring.stroke()

    # Embossed sparkle: a dark copy offset down, then the bright one on top.
    star_radius = face_radius * 0.72
    _rgb(0.60, 0.37, 0.06, 0.9).setFill()
    _sparkle(center, center - p * 0.008, star_radius).fill()
    _rgb(1.00, 0.97, 0.85).setFill()
    _sparkle(center, center, star_radius).fill()

    NSGraphicsContext.restoreGraphicsState()
    data = rep.representationUsingType_properties_(NSBitmapImageFileTypePNG, None)
    data.writeToFile_atomically_(str(path), True)


def build_icns(dest):
    with tempfile.TemporaryDirectory() as tmp:
        iconset = Path(tmp) / f"{ICON_NAME}.iconset"
        iconset.mkdir()
        for points in (16, 32, 128, 256, 512):
            render_icon_png(iconset / f"icon_{points}x{points}.png", points)
            render_icon_png(iconset / f"icon_{points}x{points}@2x.png", points * 2)
        subprocess.run(
            ["iconutil", "-c", "icns", str(iconset), "-o", str(dest)],
            check=True,
            capture_output=True,
        )


def default_dest():
    system = Path("/Applications")
    if os.access(system, os.W_OK):
        return system
    return Path.home() / "Applications"


def build(dest_dir, python, project_dir=PROJECT_DIR, icon=True):
    """Create (or replace) <dest_dir>/<APP_NAME>.app. Returns the bundle path."""
    dest_dir = Path(dest_dir)
    dest_dir.mkdir(parents=True, exist_ok=True)
    bundle = dest_dir / f"{APP_NAME}.app"
    if bundle.exists():
        shutil.rmtree(bundle)

    macos = bundle / "Contents" / "MacOS"
    resources = bundle / "Contents" / "Resources"
    macos.mkdir(parents=True)
    resources.mkdir(parents=True)

    with open(bundle / "Contents" / "Info.plist", "wb") as f:
        plistlib.dump(info_plist(), f)
    executable = macos / EXECUTABLE_NAME
    executable.write_text(launcher_script(python, Path(project_dir)))
    executable.chmod(0o755)
    if icon:
        build_icns(resources / f"{ICON_NAME}.icns")

    # Tell Finder/Launchpad about the new bundle and refresh its icon.
    lsregister = (
        "/System/Library/Frameworks/CoreServices.framework/Frameworks/"
        "LaunchServices.framework/Support/lsregister"
    )
    if Path(lsregister).exists():
        subprocess.run([lsregister, "-f", str(bundle)], capture_output=True)
    return bundle


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--python", default=shutil.which("python3") or sys.executable)
    parser.add_argument("--dest", default=str(default_dest()))
    args = parser.parse_args()
    bundle = build(args.dest, args.python)
    print(f"Built {bundle}")
    print(bundle / "Contents" / "MacOS" / EXECUTABLE_NAME)


if __name__ == "__main__":
    main()
